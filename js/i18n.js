// Language layer. Interface strings live in STR; story content uses inline {tr, en} objects through L().
const I18N = { lang: 'tr' };

function L(o) {
  if (o == null) return '';
  if (typeof o === 'string') return o;
  return o[I18N.lang] ?? o.tr ?? o.en ?? '';
}

function T(k, vars) {
  const e = STR[k];
  let s = e ? (e[I18N.lang] ?? e.tr) : k;
  if (vars) for (const v in vars) s = s.split('{' + v + '}').join(vars[v]);
  return s;
}

